function providerSortRank(provider) {
  const sourceRank = {
    publicSource: 0,
    invoiceBacked: 1,
  };

  return sourceRank[provider.sourceLabel] ?? 4;
}

function isVisibleProviderRecord(provider) {
  return Boolean(provider.sourceLabel);
}

function formatLanguageTags(provider) {
  const tags = provider.languageTags || [];
  return tags.length ? tags.join(" / ") : "Needs direct check";
}

function industryProofGuide(category) {
  if (/accounting|tax/i.test(category)) {
    return "MIA membership or tax agent approval may apply";
  }
  if (/company secretary/i.test(category)) {
    return "SSM practising certificate may apply";
  }
  if (/electrical|wiring|contractor/i.test(category)) {
    return "ST, competent person, or CIDB proof may apply";
  }
  if (/packaging/i.test(category)) {
    return "SSM record, product evidence, MOQ, and delivery terms";
  }
  return "Industry proof depends on category";
}

function matchesProviderTrustFilters(provider, filters) {
  const entityMatch = filters.entity === "All" || provider.entityType === filters.entity;
  const languageMatch = filters.language === "All" || (provider.languageTags || []).includes(filters.language);
  const proofMatch = filters.proof === "All" || (provider.proofTags || []).includes(filters.proof);
  return entityMatch && languageMatch && proofMatch;
}

function providerSignalItems(provider) {
  const isZh = currentLang === "zh";

  return [
    { label: isZh ? "注册类型" : "Entity", value: provider.entityType || "Check SSM record" },
    { label: isZh ? "语言" : "Language", value: formatLanguageTags(provider) },
    { label: isZh ? "证明" : "Proof", value: provider.proofStatus || industryProofGuide(provider.category) },
  ];
}

function providerResultSummary(shown, total, activeFilterCount) {
  const summary = t("providerResultSummary").replace("{shown}", shown).replace("{total}", total);
  if (!activeFilterCount) {
    return summary;
  }
  return `${summary} · ${t("providerFiltersActive").replace("{count}", activeFilterCount)}`;
}

function renderProviders() {
  const filter = providerFilter.value;
  const query = providerSearch.value.trim().toLowerCase();
  const trustFilters = {
    entity: providerEntityFilter.value,
    language: providerLanguageFilter.value,
    proof: providerProofFilter.value,
  };
  const filtered = providers
    .filter((provider) => {
      const matchesFilter = filter === "All" || provider.category === filter;
      return (
        isVisibleProviderRecord(provider) &&
        matchesFilter &&
        matchesProviderTrustFilters(provider, trustFilters) &&
        providerSearchText(provider).includes(query)
      );
    })
    .sort((a, b) => providerSortRank(a) - providerSortRank(b) || a.name.localeCompare(b.name));
  const visibleTotal = providers.filter(isVisibleProviderRecord).length;
  const activeFilterCount = [
    filter !== "All",
    query.length > 0,
    trustFilters.entity !== "All",
    trustFilters.language !== "All",
    trustFilters.proof !== "All",
  ].filter(Boolean).length;

  providerStatus.textContent = providerResultSummary(filtered.length, visibleTotal, activeFilterCount);

  providerGrid.innerHTML =
    filtered
      .map(
        (provider) => `
          <article class="provider-card">
            <div class="provider-top">
              <div>
                <h3>${currentLang === "zh" ? provider.zhName : provider.name}</h3>
                <p>${currentLang === "zh" ? provider.zhCategory : provider.category}</p>
              </div>
              ${provider.verified && !provider.sourceLabel ? `<span class="verified">${t("profileChecked")}</span>` : ""}
              ${provider.sourceLabel ? `<span class="verified muted-badge">${t(provider.sourceLabel)}</span>` : ""}
            </div>
            <p>${currentLang === "zh" ? provider.zhSummary : provider.summary}</p>
            <div class="provider-signals">
              ${providerSignalItems(provider)
                .map(
                  (signal) => `
                    <span>
                      <small>${signal.label}</small>
                      ${signal.value}
                    </span>
                  `,
                )
                .join("")}
            </div>
            ${
              provider.verificationNote
                ? `<p class="provider-note">${currentLang === "zh" ? provider.zhVerificationNote || provider.verificationNote : provider.verificationNote} ${provider.proofNote ? `<span>${provider.proofNote}</span>` : ""}</p>`
                : ""
            }
            <div class="provider-meta">
              <span class="pill">${
                currentLang === "zh" ? provider.zhCategory.replace("马来西亚", "").trim() : provider.category.replace(" Malaysia", "")
              }</span>
              <span class="pill">${t("canReceiveEnquiries")}</span>
            </div>
            <div class="card-actions">
              ${
                provider.detailsUrl
                  ? `<a class="text-link" href="${provider.detailsUrl}">${t("viewGuide")}</a>`
                  : ""
              }
              <button class="button secondary small" type="button" data-provider-service="${provider.category}" data-provider-location="${provider.location}">${t("contactProvider")}</button>
            </div>
          </article>
        `,
      )
      .join("") || `<p class="empty-state">${t("noProviderMatch")}</p>`;

  providerGrid.querySelectorAll("[data-provider-service]").forEach((button) => {
    button.addEventListener("click", () => {
      const category = categories.find((item) => item.name === button.dataset.providerService);
      quoteForCategory(category, button.dataset.providerLocation);
    });
  });
}

function setupSiteSearch() {
  siteSearchButton.addEventListener("click", applySiteSearch);
  siteSearch.addEventListener("keydown", (event) => {
    if (event.key === "Enter") {
      event.preventDefault();
      applySiteSearch();
    }
  });

  const initialQuery = new URLSearchParams(window.location.search).get("q");
  if (initialQuery) {
    siteSearch.value = initialQuery;
    window.setTimeout(() => {
      applySiteSearch();
      if (window.location.hash) {
        window.setTimeout(() => scrollToElement(window.location.hash), 150);
      }
    }, 0);
  }
}

