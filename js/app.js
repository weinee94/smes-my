function setupLeadForms() {
  document.querySelectorAll(".js-lead-form").forEach((form) => {
    const status = form.querySelector(".form-status");

    form.addEventListener(
      "invalid",
      () => {
        status.className = "form-status error";
        status.textContent = t("requiredFields");
      },
      true,
    );

    form.addEventListener("submit", async (event) => {
      event.preventDefault();
      status.className = "form-status";

      if (form.action.includes("REPLACE_WITH_DEPLOYMENT_ID")) {
        status.textContent = t("endpointMissing");
        status.classList.add("error");
        return;
      }

      const button = form.querySelector("button[type='submit']");
      button.disabled = true;
      button.textContent = t("sending");
      status.textContent = t("submitting");

      try {
        const payload = new FormData(form);
        payload.set("page_url", window.location.href);
        payload.set("user_agent", navigator.userAgent);

        const timeout = new Promise((_, reject) => {
          window.setTimeout(() => reject(new Error("Submission timed out")), 15000);
        });

        await Promise.race([
          fetch(form.action, {
            method: "POST",
            body: payload,
            mode: "no-cors",
          }),
          timeout,
        ]);

        form.reset();
        status.textContent =
          form.dataset[`success${currentLang === "zh" ? "Zh" : "En"}`] ||
          form.dataset.success ||
          "Thanks. Your request has been received.";
        status.classList.add("success");
      } catch (error) {
        status.textContent = t("submitFailed");
        status.classList.add("error");
      } finally {
        button.disabled = false;
        button.textContent = button.dataset.i18n ? t(button.dataset.i18n) : form.dataset.buttonLabel || button.dataset.originalLabel || "Submit";
      }
    });

    const button = form.querySelector("button[type='submit']");
    if (button) {
      button.dataset.originalLabel = button.textContent;
      form.dataset.buttonLabel = button.textContent;
    }
  });
}

function t(key) {
  return translations[currentLang][key] || translations.en[key] || key;
}

function localizePage() {
  document.documentElement.lang = currentLang === "zh" ? "zh-Hans" : "en";
  document.body.classList.toggle("is-zh", currentLang === "zh");

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    element.placeholder = t(element.dataset.i18nPlaceholder);
  });

  document.querySelectorAll("[data-lang]").forEach((button) => {
    button.classList.toggle("active", button.dataset.lang === currentLang);
    button.setAttribute("aria-pressed", button.dataset.lang === currentLang ? "true" : "false");
  });
}

function setupLanguageSwitch() {
  document.querySelectorAll("[data-lang]").forEach((button) => {
    button.addEventListener("click", () => {
      currentLang = button.dataset.lang;
      localStorage.setItem("smesLang", currentLang);
      localizePage();
      renderCategories();
      populateProviderFilter();
      renderProviders();
    });
  });
}

function renderCategories() {
  categoryGrid.innerHTML = categories
    .map(
      (category) => `
        <a class="category-card" href="${category.url || "#quote"}">
          <div>
            <h3>${currentLang === "zh" ? category.zhName : category.name}</h3>
            <p>${currentLang === "zh" ? category.zhSummary : category.summary}</p>
          </div>
          <strong class="category-count">${currentLang === "zh" ? category.zhCount : category.count}</strong>
          <div class="category-meta">
            ${(currentLang === "zh" ? category.zhTags : category.tags).map((tag) => `<span class="pill">${tag}</span>`).join("")}
          </div>
        </a>
      `,
    )
    .join("");
}

function populateProviderFilter() {
  providerFilter.innerHTML = `<option value="All">${t("allCategories")}</option>`;
  categories.forEach((category) => {
    const option = document.createElement("option");
    option.value = category.name;
    option.textContent =
      currentLang === "zh" ? category.zhName.replace("马来西亚", "").trim() : category.name.replace(" Malaysia", "");
    providerFilter.append(option);
  });
}

function renderProviders() {
  const filter = providerFilter.value;
  const query = providerSearch.value.trim().toLowerCase();
  const filtered = providers.filter((provider) => {
    const matchesFilter = filter === "All" || provider.category === filter;
    const content = `${provider.name} ${provider.category} ${provider.location} ${provider.summary}`.toLowerCase();
    return matchesFilter && content.includes(query);
  });

  providerGrid.innerHTML =
    filtered
      .map(
        (provider) => `
          <article class="provider-card">
            <div class="provider-top">
              <div>
                <h3>${currentLang === "zh" ? provider.zhName : provider.name}</h3>
                <p>${currentLang === "zh" ? provider.zhCategory : provider.category}</p>
              </div>
              ${provider.verified ? `<span class="verified">${t("profileChecked")}</span>` : ""}
            </div>
            <p>${currentLang === "zh" ? provider.zhSummary : provider.summary}</p>
            <div class="provider-signals">
              <span>${currentLang === "zh" ? provider.zhLocation || provider.location : provider.location}</span>
              <span>${provider.response}</span>
              <span>${provider.languages}</span>
            </div>
            <div class="provider-meta">
              <span class="pill">${
                currentLang === "zh" ? provider.zhCategory.replace("马来西亚", "").trim() : provider.category.replace(" Malaysia", "")
              }</span>
              <span class="pill">${t("canReceiveEnquiries")}</span>
            </div>
          </article>
        `,
      )
      .join("") || `<p>${t("noProviderMatch")}</p>`;
}

